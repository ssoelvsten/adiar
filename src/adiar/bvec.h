  bvec
  bvec_xor(const bvec& x, const bvec& y);

  ////////////////////////////////////////////////////////////////////////////////////////////////
  /// \brief Bitwise negation of a bitvectors.
  ////////////////////////////////////////////////////////////////////////////////////////////////
  bvec
  bvec_not(const bvec& x);

