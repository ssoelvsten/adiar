  /// \{

  ////////////////////////////////////////////////////////////////////////////////////////////////
  /// \brief Equality comparison of BDDs
  ////////////////////////////////////////////////////////////////////////////////////////////////
  bool
  bvec_equal(const bvec& x, const bvec& y);

  //////////////////////////////////////////////////////////////////////////////////////////////////
  /// \see bvec_equal
  //////////////////////////////////////////////////////////////////////////////////////////////////
  bool
  operator==(const bvec& x, const bvec& y);

  /// \}
  /// \}
  //////////////////////////////////////////////////////////////////////////////////////////////////

