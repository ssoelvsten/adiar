  ////////////////////////////////////////////////////////////////////////////////////////////////
  /// \brief Arithmetic addition of two symbolic bit-vectors.
  ////////////////////////////////////////////////////////////////////////////////////////////////
  bvec
  bvec_add(const bvec& x, const bvec& y);

  //////////////////////////////////////////////////////////////////////////////////////////////////
  /// \see bvec_add
  //////////////////////////////////////////////////////////////////////////////////////////////////
  inline bvec
  operator+(const bvec& x, const bvec& y)
  {
    return bvec_add(x, y);
  }

  ////////////////////////////////////////////////////////////////////////////////////////////////
  /// \brief Arithmetic subtraction of two symbolic bit-vectors.
  ///
  /// \details If `x < y`, then this will result in an underflow with `y.size()` bits.
  ////////////////////////////////////////////////////////////////////////////////////////////////
  bvec
  bvec_sub(const bvec& x, const bvec& y);

  /// \}
  /// \}
  //////////////////////////////////////////////////////////////////////////////////////////////////

