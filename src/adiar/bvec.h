  ////////////////////////////////////////////////////////////////////////////////////////////////
  /// \brief Bitwise disjunction of two bitvectors, upcasting the `bitlen` if needed.
  ////////////////////////////////////////////////////////////////////////////////////////////////
  bvec
  bvec_or(const bvec& x, const bvec& y);

  ////////////////////////////////////////////////////////////////////////////////////////////////
  /// \brief Bitwise exclusive disjunction of two bitvectors, upcasting the `bitlen` if needed.
